const DAY = 86_400_000;

function at(now: Date, days: number, hours = 10, minutes = 0): string {
  const date = new Date(now.getTime() + days * DAY);
  date.setHours(hours, minutes, 0, 0);
  return date.toISOString();
}

function iso(now: Date, days: number): string {
  return new Date(now.getTime() + days * DAY).toISOString();
}

function dateOnly(now: Date, days: number): string {
  return iso(now, days).slice(0, 10);
}

function makeActivity(type: ActivityType, params: Record<string, string | number>, atIso: string, index: number): Activity {
  const template = ACTIVITY_MESSAGES[`activity.${type}`] ?? { fr: type, en: type };
  return {
    id: `seed_act_${index}`,
    at: atIso,
    type,
    message: { fr: formatTemplate(template.fr, params), en: formatTemplate(template.en, params) },
  };
}

function stageHistory(stages: { stage: Stage; days: number; note?: string }[], now: Date) {
  return stages.map((entry) => ({ stage: entry.stage, at: iso(now, entry.days), note: entry.note }));
}

